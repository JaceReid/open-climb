/// <reference types="node" />
// Keeps docs/claude-prompt.md in sync with the prompt the app generates for a
// fresh install. Regenerate with: UPDATE_DOCS=1 npm test
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { BUILT_IN_EXERCISES, BUILT_IN_WORKOUTS } from '@/data/library';

import { buildClaudePrompt } from './prompt';

const DOC = fileURLToPath(new URL('../../../docs/claude-prompt.md', import.meta.url));

const HEADER = `<!-- Generated by src/lib/import/docs.test.ts. Do not edit; run \`UPDATE_DOCS=1 npm test\`. -->

# Prompt for Claude

The app's **Settings → Plan with Claude → Copy prompt** button copies this
text, with your own custom exercises and workouts added to the library lists.
You can also paste it into a Claude Project's instructions so every chat in that
project already knows the format.

---

`;

describe('docs/claude-prompt.md', () => {
  it('matches the generated prompt', () => {
    const expected = HEADER + buildClaudePrompt(BUILT_IN_EXERCISES, BUILT_IN_WORKOUTS) + '\n';
    if (process.env.UPDATE_DOCS) writeFileSync(DOC, expected);
    expect(readFileSync(DOC, 'utf8')).toBe(expected);
  });
});
